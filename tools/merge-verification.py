"""Merge trusted, reviewed Gradle baselines for all entry points.

--official-cache includes hashes from the optional official-repository cache, so
OS-specific native classifiers are verified on CI as well as this Windows host.
This command changes the trust baseline; do not use it to bypass an unexpected
checksum mismatch. It never downloads or resolves dependencies.
"""
from pathlib import Path
import argparse
import hashlib
import json
import re
import xml.etree.ElementTree as ET

root = Path(__file__).resolve().parent.parent
parser = argparse.ArgumentParser()
parser.add_argument('--official-cache', type=Path)
parser.add_argument('--loom-cache', type=Path, help='Reviewed generated mappings; validates Mojang inputs before adding hashes')
args = parser.parse_args()
ns = 'https://schema.gradle.org/dependency-verification'
ET.register_namespace('', ns)
ET.register_namespace('xsi', 'http://www.w3.org/2001/XMLSchema-instance')
components = {}
trust_fields=('group','name','version','file')
allowed_trusts={('loom','mappings','layered+hash.2198','mappings-layered+hash.2198.jar')}
game_baseline=root/'gradle/generated-game-checksums.json'
if game_baseline.exists():
    for target in json.loads(game_baseline.read_text(encoding='utf-8'))['targets'].values():
        for artifact in target['artifacts']:
            allowed_trusts.add(tuple(artifact[field] for field in trust_fields))
for entry in ('legacy', 'modern'):
    path = root / entry / 'gradle/verification-metadata.xml'
    tree = ET.parse(path)
    config = tree.find(f'{{{ns}}}configuration')
    assert config.findtext(f'{{{ns}}}verify-metadata') == 'true'
    assert config.findtext(f'{{{ns}}}verify-signatures') == 'false'
    trusted=config.find(f'{{{ns}}}trusted-artifacts')
    if trusted is not None:
        for item in trusted:
            assert item.tag==f'{{{ns}}}trust'
            assert tuple(item.get(key) for key in trust_fields) in allowed_trusts
            assert item.get('regex','false')=='false'
    for component in tree.findall(f'{{{ns}}}components/{{{ns}}}component'):
        key = tuple(component.get(field) for field in ('group','name','version'))
        artifacts = components.setdefault(key, {})
        for artifact in component:
            checksums = artifacts.setdefault(artifact.get('name'), {})
            for checksum in artifact:
                assert checksum.tag == f'{{{ns}}}sha256'
                checksums[checksum.get('value')] = checksum.get('origin','Generated by Gradle')
                for alternative in checksum:
                    assert alternative.tag == f'{{{ns}}}also-trust'
                    checksums[alternative.get('value')] = checksum.get('origin','Generated by Gradle')

if args.loom_cache:
    import json
    import zipfile
    versions = {t['minecraft'] for t in json.loads((root/'gradle/targets.json').read_text(encoding='utf-8'))['targets'] if t['java']==21}
    for version in sorted(versions):
        directory=args.loom_cache.resolve()/version
        manifest=json.loads((directory/'mojang_minecraft_info.json').read_text(encoding='utf-8'))
        assert manifest['id']==version
        for kind in ('client','server'):
            source=directory/'layered/working_dir/layered_hash_2198/mojang'/f'{kind}.txt'
            assert hashlib.sha1(source.read_bytes()).hexdigest()==manifest['downloads'][kind+'_mappings']['sha1'], f'Mojang mapping input mismatch: {version} {kind}'
        generated=directory/'layered/loom.mappings-layered+hash.2198.jar'
        with zipfile.ZipFile(generated) as jar:
            assert jar.testzip() is None
            assert jar.read('mappings/mappings.tiny').startswith(b'tiny\t2\t0\tintermediary\tnamed')
        checksums=components.setdefault(('loom','mappings','layered+hash.2198'),{}).setdefault('mappings-layered+hash.2198.jar',{})
        checksums[hashlib.sha256(generated.read_bytes()).hexdigest()]=f'Loom generated mappings; Mojang {version} input hashes checked'

if args.official_cache:
    cache = args.official_cache.resolve()
    for path in sorted(cache.rglob('*')):
        if not path.is_file() or path.suffix not in ('.pom','.module','.jar','.zip'):
            continue
        parts = path.relative_to(cache).parts
        if len(parts) < 4: continue
        group, name, version = '.'.join(parts[:-3]), parts[-3], parts[-2]
        if not all(re.fullmatch(r'[\w.+-]+', value) for value in (group,name,version)):
            raise ValueError(f'Unexpected cache coordinate: {path}')
        if not path.name.startswith(f'{name}-{version}'):
            continue
        digest = hashlib.sha256(path.read_bytes()).hexdigest()
        checksums = components.setdefault((group,name,version),{}).setdefault(path.name,{})
        checksums.setdefault(digest, 'Official repository cache; see docs/building.md')

result = ET.Element(f'{{{ns}}}verification-metadata', {
    '{http://www.w3.org/2001/XMLSchema-instance}schemaLocation': f'{ns} {ns}/dependency-verification-1.3.xsd'})
configuration = ET.SubElement(result, f'{{{ns}}}configuration')
ET.SubElement(configuration, f'{{{ns}}}verify-metadata').text = 'true'
ET.SubElement(configuration, f'{{{ns}}}verify-signatures').text = 'false'
trusted=ET.SubElement(configuration,f'{{{ns}}}trusted-artifacts')
for coordinate in sorted(allowed_trusts):
    ET.SubElement(trusted,f'{{{ns}}}trust',dict(zip(trust_fields,coordinate)),reason='Loom generated ZIP timestamps; full contents and Mojang inputs pinned by verifyGeneratedMappings / verifyGeneratedGame')
container = ET.SubElement(result, f'{{{ns}}}components')
for (group,name,version), artifacts in sorted(components.items()):
    component = ET.SubElement(container, f'{{{ns}}}component', dict(group=group,name=name,version=version))
    for artifact_name, checksums in sorted(artifacts.items()):
        artifact = ET.SubElement(component,f'{{{ns}}}artifact',dict(name=artifact_name))
        values=sorted(checksums.items())
        checksum=ET.SubElement(artifact,f'{{{ns}}}sha256',dict(value=values[0][0],origin=values[0][1]))
        for value, origin in values[1:]:
            ET.SubElement(checksum,f'{{{ns}}}also-trust',dict(value=value))
ET.indent(result, space='   ')
for entry in ('', 'legacy', 'modern'):
    destination = root / entry / 'gradle/verification-metadata.xml'
    ET.ElementTree(result).write(destination,encoding='utf-8',xml_declaration=True)
print(f'{len(components)} dependency coordinates merged; all entry points share one checksum baseline')
